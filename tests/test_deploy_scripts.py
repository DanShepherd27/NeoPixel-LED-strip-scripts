"""Tests for deploy helper scripts: python -m unittest discover tests"""

import shutil
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "deploy" / "make-asound-conf.sh"


@unittest.skipIf(shutil.which("bash") is None, "bash is not installed")
class AsoundConfTests(unittest.TestCase):
    def render(self, *args):
        return subprocess.run(["bash", str(SCRIPT), *args], capture_output=True, text=True, check=False)

    def test_mixer_wraps_the_raw_hardware_device(self):
        result = self.render("plughw:CARD=U192k,DEV=0", "4", "48000", "speexrate_medium")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('pcm "hw:CARD=U192k,DEV=0"', result.stdout)
        self.assertNotIn("plughw", result.stdout)

    def test_channels_rate_and_converter_are_applied(self):
        out = self.render("hw:1,0", "4", "44100", "linear").stdout
        self.assertIn("channels 4", out)
        self.assertIn("rate 44100", out)
        self.assertIn('defaults.pcm.rate_converter "linear"', out)

    def test_exposes_the_arcade_out_device_and_marks_the_file_as_generated(self):
        out = self.render("hw:1,0", "2", "48000", "linear").stdout
        self.assertIn("pcm.arcade_out {", out)
        self.assertIn("type dmix", out)
        self.assertTrue(out.startswith("# Generated by led-arcade"))

    def test_missing_arguments_fail(self):
        self.assertEqual(self.render("hw:1,0").returncode, 2)


if __name__ == "__main__":
    unittest.main()
