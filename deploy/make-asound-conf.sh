#!/usr/bin/env bash
# Print an /etc/asound.conf that adds a software mixer, so game sounds, the song show and
# phone audio can play through one sound card together.
#   usage: make-asound-conf.sh HARDWARE_DEVICE CHANNELS RATE RATE_CONVERTER
#   e.g.:  make-asound-conf.sh hw:CARD=U192k,DEV=0 4 48000 speexrate_medium
# Point LED_OUTPUT_AUDIO_DEVICE at "arcade_out" to use it.
set -euo pipefail

if [ "$#" -ne 4 ]; then
    echo "usage: $0 HARDWARE_DEVICE CHANNELS RATE RATE_CONVERTER" >&2
    exit 2
fi
# The mixer needs the raw hardware device; a plug wrapper there would convert twice.
HARDWARE="${1/#plughw:/hw:}"
CHANNELS="$2"
RATE="$3"
CONVERTER="$4"

cat <<CONF
# Generated by led-arcade deploy/install.sh; delete this line to keep your own edits.
# Every program plays to arcade_out; ALSA mixes them in software for the sound card.
defaults.pcm.rate_converter "$CONVERTER"

pcm.arcade_out {
    type plug
    slave.pcm "arcade_dmix"
}

pcm.arcade_dmix {
    type dmix
    ipc_key 5151
    ipc_perm 0666
    slave {
        pcm "$HARDWARE"
        rate $RATE
        channels $CHANNELS
        period_size 1024
        buffer_size 4096
    }
    bindings {
        0 0
        1 1
    }
}
CONF
